const locales = { en, fa, ar };

const RTL_LANGS = new Set(['fa', 'ar']);

/**
 * @param {'en' | 'fa' | 'ar' | string} language
 */
export function resolveLanguage(language = 'en') {
  const key = String(language || 'en').toLowerCase();
  if (locales[key]) return key;
  return 'en';
}

/**
 * @param {'en' | 'fa' | 'ar' | string} language
 */
export function getMessages(language = 'en') {
  return locales[resolveLanguage(language)];
}

/**
 * @param {'en' | 'fa' | 'ar' | string} language
 */
export function getDefaultDir(language = 'en') {
  return RTL_LANGS.has(resolveLanguage(language)) ? 'rtl' : 'ltr';
}

export function getBlockOptions(t) {
  return [
    { value: 'p', label: t.paragraph },
    { value: 'h1', label: t.heading1 },
    { value: 'h2', label: t.heading2 },
    { value: 'h3', label: t.heading3 },
    { value: 'h4', label: t.heading4 },
    { value: 'h5', label: t.heading5 },
    { value: 'h6', label: t.heading6 },
    { value: 'blockquote', label: t.quote },
    { value: 'pre', label: t.preformatted },
  ];
}

